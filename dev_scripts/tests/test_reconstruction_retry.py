"""Rejected reconstruction retries must not corrupt other code-object indices."""
import unittest
from types import SimpleNamespace
from unittest.mock import Mock, call, patch
from pylingual.decompiler import Decompiler


def result(code=None, success=False):
    return SimpleNamespace(success=success, bc_a=None if code is None else SimpleNamespace(codeobj=code))


class ReconstructionRetryTests(unittest.TestCase):
    def fixture(self, verification):
        value=object.__new__(Decompiler)
        value.ordered_bytecodes=[SimpleNamespace(codeobj="original", name="fixture")]
        value.ordered_instructions=[[object(),object()]]
        value.segmentation_results=[[{"entity":"B"},{"entity":"B"}]]
        value.translation_results=[["original one","original two"]]
        value.source_lines=["original one","original two"]
        value.indented_source="original one\noriginal two"
        value.source_context=SimpleNamespace(cfts={"original":object()},update_lines=Mock())
        value.equivalence_results=[result("original")]
        value.top_k=2;value.highest_k_used=0
        value.update_starts_line=Mock()
        value.make_translation_request=Mock(return_value=["request"])
        value.translator=Mock(return_value=["candidate"])
        value.unmask_lines=Mock()
        value.update_source_lines=lambda:setattr(value,"source_lines",list(value.translation_results[0]))
        value.reconstruct_source=lambda:setattr(value,"indented_source","\n".join(value.source_lines))
        value.check_reconstruction=Mock(return_value=verification)
        return value

    def retry(self,value):
        with patch("pylingual.decompiler.has_comp_error",return_value=False),patch("pylingual.decompiler.get_top_k_predictions",return_value=[["B","B"],["B","I"]]):
            return value.correct_segmentation(0)

    def test_rejected_candidate_restores_translation_and_source(self):
        value=self.fixture([result("original")])
        old_translation=value.translation_results[0];old_lines=value.source_lines;old_source=value.indented_source
        self.assertFalse(self.retry(value))
        self.assertIs(value.translation_results[0],old_translation)
        self.assertIs(value.source_lines,old_lines)
        self.assertEqual(value.indented_source,old_source)
        self.assertEqual([row["entity"] for row in value.segmentation_results[0]],["B","B"])
        self.assertIs(value.source_context.update_lines.call_args.args[0],old_lines)

    def test_target_success_is_matched_by_original_code_not_result_position(self):
        extra=result();verification=[extra,result("original",True)]
        value=self.fixture(verification)
        self.assertTrue(self.retry(value))
        self.assertIs(value.equivalence_results,verification)
        self.assertFalse(extra.success)  # Extra generated bytecode remains a verification failure.
        self.assertEqual(value.translation_results[0],["candidate"])
        self.assertEqual(value.highest_k_used,1)

    def test_unrelated_success_does_not_accept_failed_original(self):
        value=self.fixture([result("other",True),result("original")])
        self.assertFalse(self.retry(value))
        self.assertEqual(value.translation_results[0],["original one","original two"])

    def test_missing_original_does_not_accept_unrelated_result(self):
        value=self.fixture([result("other",True)])
        self.assertFalse(self.retry(value))

    def failures(self,verification,codes):
        value=object.__new__(Decompiler)
        value.equivalence_results=verification
        value.ordered_bytecodes=[SimpleNamespace(codeobj=code) for code in codes]
        value.correct_segmentation=Mock(return_value=False)
        with patch("pylingual.decompiler.has_comp_error",return_value=False),patch("pylingual.decompiler.TrackedList",side_effect=lambda step,items:items):
            value.correct_failures()
        return value

    def test_extra_bytecode_does_not_shift_original_retry_index(self):
        extra=result();verification=[extra,result("original")]
        value=self.failures(verification,["original"])
        self.assertEqual(value.correct_segmentation.call_args_list,[call(0)])
        self.assertIs(value.equivalence_results,verification)
        self.assertFalse(extra.success)

    def test_reordered_results_use_original_object_indices(self):
        value=self.failures([result("third"),result("first"),result("second",True)],["first","second","third"])
        self.assertEqual(value.correct_segmentation.call_args_list,[call(0),call(2)])

    def test_extra_only_failure_is_retained_without_invalid_retry(self):
        extra=result();value=self.failures([result("original",True),extra],["original"])
        value.correct_segmentation.assert_not_called()
        self.assertFalse(extra.success)

if __name__=="__main__":unittest.main()
